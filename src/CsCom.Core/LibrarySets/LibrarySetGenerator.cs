using CsCom.CodeGeneration;
using CsCom.Configuration;
using CsCom.Model;
using CsCom.Output;
using CsCom.TypeLibraries;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.Extensions.Logging;
using Microsoft.Extensions.Logging.Abstractions;

namespace CsCom.LibrarySets;

/// <summary>
/// Generates several type libraries or interop assemblies into one project, each into its own namespace.
/// </summary>
/// <remarks>
/// <para>
/// The types that the references use from other libraries are generated once, into the namespace of their library,
/// <c>Interop.&lt;Library&gt;</c>: all the types of a library that is a reference, otherwise the types that any of the
/// references use. The configuration file of a reference applies to its library; the libraries that are only used by the
/// references are generated with the default options and without a configuration.
/// </para>
/// <para>The support code is generated once, see <see cref="LibrarySetOptions.SupportNamespace"/>.</para>
/// </remarks>
public sealed partial class LibrarySetGenerator
{
    /// <summary>The name of the file with the assembly attributes, see <see cref="LibrarySetOptions.DisableRuntimeMarshalling"/>.</summary>
    public const string AssemblyAttributesFileName = "CsComAssemblyAttributes.cs";

    private const string DefaultSupportNamespace = "Interop.ComSupport";

    // The folder of the support code generated by the emitter.
    private const string SupportCodeFolder = "ComSupport/";

    private readonly InteropPipeline _pipeline;
    private readonly ILogger _logger;

    /// <summary>
    /// Initializes a new instance of the <see cref="LibrarySetGenerator"/> class.
    /// </summary>
    /// <param name="pipeline">The pipeline that reads, transforms and generates each library.</param>
    /// <param name="loggerFactory">The logger factory.</param>
    public LibrarySetGenerator(InteropPipeline pipeline, ILoggerFactory? loggerFactory = null)
    {
        ArgumentNullException.ThrowIfNull(pipeline);
        _pipeline = pipeline;
        _logger = (loggerFactory ?? NullLoggerFactory.Instance).CreateLogger<LibrarySetGenerator>();
    }

    /// <summary>
    /// Reads the references and generates the code of their libraries and of the types they use from other libraries.
    /// </summary>
    /// <param name="references">The references.</param>
    /// <param name="options">The options.</param>
    /// <returns>The generated files, in a folder per namespace.</returns>
    /// <exception cref="CsComException">A reference or a configuration file is not valid, or two libraries have the same namespace.</exception>
    public LibrarySetResult Generate(IReadOnlyList<LibrarySetReference> references, LibrarySetOptions options)
    {
        ArgumentNullException.ThrowIfNull(references);
        ArgumentNullException.ThrowIfNull(options);
        if (references.Count == 0)
        {
            throw new CsComException("No type library or interop assembly is referenced.");
        }

        string supportNamespace = options.SupportNamespace ?? DefaultSupportNamespace;
        if (options.SupportCode != SupportCodeMode.Package)
        {
            ProjectGenerator.ValidateNamespace(supportNamespace);
        }

        var inputFiles = new List<string>();
        var models = new List<(LibrarySetReference, TypeLibrary, PipelineConfiguration)>();
        foreach (var reference in references)
        {
            var library = _pipeline.ReadTypeLibrary(reference.Source, reference.ReferencePaths);
            if (library.Path is { } path)
            {
                inputFiles.Add(TypeLibrarySource.GetFilePath(path));
            }

            var configuration = PipelineConfiguration.Empty;
            if (!string.IsNullOrEmpty(reference.ConfigurationPath))
            {
                string configurationPath = Path.GetFullPath(reference.ConfigurationPath);
                configuration = PipelineConfiguration.Load(configurationPath, _pipeline.Registry);
                inputFiles.Add(configurationPath);
            }

            models.Add((reference, library, configuration));
        }

        var entries = LibrarySetMerger.Merge(models, _logger);
        if (options.SupportCode != SupportCodeMode.Package && entries.Find(e => string.Equals(e.Namespace, supportNamespace, StringComparison.OrdinalIgnoreCase)) is { } conflict)
        {
            throw new CsComException($"The support code cannot be generated into '{supportNamespace}', the namespace of '{conflict.Library.Name}'.");
        }

        var libraries = new List<(LibrarySetEntry Entry, CodeGenerationOptions Options)>();
        foreach (var entry in entries)
        {
            var codeOptions = CreateOptions(entry, options, supportNamespace);
            if (entry.Reference is null)
            {
                LogGeneratingUsedTypes(entry.Library.Name, entry.Namespace);
            }
            else
            {
                LogGeneratingLibrary(entry.Library.Name, entry.Namespace);
            }

            _pipeline.TransformModel(entry.Library, codeOptions, entry.Configuration);
            libraries.Add((entry, codeOptions));
        }

        LibrarySetMerger.ValidateReferences(entries);
        var namespaces = new Dictionary<TypeDefinition, string>(ReferenceEqualityComparer.Instance);
        foreach (var entry in entries)
        {
            foreach (var type in entry.Library.Types)
            {
                namespaces.Add(type, entry.Namespace);
            }
        }

        var eventSources = EventEmitter.GetEventSources(entries.SelectMany(static e => e.Library.Types));
        var documents = new List<GeneratedDocument>();
        for (int i = 0; i < libraries.Count; i++)
        {
            var (entry, codeOptions) = libraries[i];
            var scope = new EmitScope { Namespaces = namespaces, EventSources = eventSources, EmitSupportCode = i == 0 };
            foreach (var document in _pipeline.EmitCode(entry.Library, codeOptions, entry.Configuration, scope))
            {
                // The support code is generated with the first library, into its own folder.
                string path = document.RelativePath.StartsWith(SupportCodeFolder, StringComparison.Ordinal)
                    ? $"{supportNamespace}/{document.RelativePath[SupportCodeFolder.Length..]}"
                    : $"{entry.Namespace}/{document.RelativePath}";
                documents.Add(document with { RelativePath = path });
            }
        }

        if (options.DisableRuntimeMarshalling)
        {
            documents.Add(CreateAssemblyAttributes(options));
        }

        return new LibrarySetResult
        {
            Documents = documents,
            Libraries = [.. entries.Select(static e => new LibrarySetLibrary(
                e.Library.Name, e.Library.Guid, e.Library.MajorVersion, e.Library.MinorVersion, e.Namespace, e.Reference is not null, e.Library.Types.Count))],
            InputFiles = [.. inputFiles.Distinct(StringComparer.OrdinalIgnoreCase)],
        };
    }

    private static CodeGenerationOptions CreateOptions(LibrarySetEntry entry, LibrarySetOptions options, string supportNamespace)
    {
        var reference = entry.Reference;
        return new CodeGenerationOptions
        {
            Namespace = entry.Namespace,
            LanguageVersion = options.LanguageVersion,
            SupportCode = options.SupportCode,
            SupportNamespace = supportNamespace,
            Marshalling = reference?.Marshalling.Apply(options.Marshalling) ?? options.Marshalling,
            EventStyle = reference?.EventStyle ?? options.EventStyle,
            StructProperties = reference?.StructProperties ?? options.StructProperties,
            OverloadsForDefaultValues = reference?.OverloadsForDefaultValues ?? options.OverloadsForDefaultValues,
            SuppressedWarnings = options.SuppressedWarnings,
            ToolVersion = options.ToolVersion,
        };
    }

    private static GeneratedDocument CreateAssemblyAttributes(LibrarySetOptions options)
    {
        string text = $"""
            // <auto-generated>
            //     This code was generated by CsCom {options.ToolVersion}.
            //     Changes to this file may cause incorrect behavior and will be lost if the code is regenerated.
            // </auto-generated>

            // Source-generated COM interop marshals VARIANT and DECIMAL values only when runtime marshalling is disabled.
            [assembly: global::System.Runtime.CompilerServices.DisableRuntimeMarshalling]

            """;
        return new GeneratedDocument(AssemblyAttributesFileName, SyntaxFactory.ParseCompilationUnit(text.ReplaceLineEndings(SyntaxFormatter.EndOfLine)));
    }

    [LoggerMessage(Level = LogLevel.Information, Message = "Generating '{Library}' into '{Namespace}'")]
    private partial void LogGeneratingLibrary(string library, string @namespace);

    [LoggerMessage(Level = LogLevel.Information, Message = "Generating the types used from '{Library}' into '{Namespace}'")]
    private partial void LogGeneratingUsedTypes(string library, string @namespace);
}
