using CsCom.CodeGeneration;
using CsCom.Configuration;
using CsCom.Model;
using CsCom.Output;
using CsCom.TypeLibraries;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.Extensions.Logging;
using Microsoft.Extensions.Logging.Abstractions;

namespace CsCom.LibrarySets;

/// <summary>
/// Generates several type libraries or interop assemblies into one project, each into its own namespace.
/// </summary>
/// <remarks>
/// <para>
/// The types that the references use from other libraries are generated once, into the namespace of their library,
/// <c>Interop.&lt;Library&gt;</c>: all the types of a library that is a reference, otherwise the types that any of the
/// references use. The configuration file of a reference applies to its library; the libraries that are only used by the
/// references are generated with the default options, and the namespaces and the configuration files of
/// <see cref="LibrarySetOptions"/> by library name.
/// </para>
/// <para>The support code is generated once, see <see cref="LibrarySetOptions.SupportNamespace"/>.</para>
/// </remarks>
public sealed partial class LibrarySetGenerator
{
    /// <summary>The name of the file with the assembly attributes, see <see cref="LibrarySetOptions.DisableRuntimeMarshalling"/>.</summary>
    public const string AssemblyAttributesFileName = "CsComAssemblyAttributes.cs";

    // The folder of the support code generated by the emitter.
    private const string SupportCodeFolder = "ComSupport/";

    private readonly InteropPipeline _pipeline;
    private readonly ILogger _logger;

    /// <summary>
    /// Initializes a new instance of the <see cref="LibrarySetGenerator"/> class.
    /// </summary>
    /// <param name="pipeline">The pipeline that reads, transforms and generates each library.</param>
    /// <param name="loggerFactory">The logger factory.</param>
    public LibrarySetGenerator(InteropPipeline pipeline, ILoggerFactory? loggerFactory = null)
    {
        ArgumentNullException.ThrowIfNull(pipeline);
        _pipeline = pipeline;
        _logger = (loggerFactory ?? NullLoggerFactory.Instance).CreateLogger<LibrarySetGenerator>();
    }

    /// <summary>
    /// Reads the references and generates the code of their libraries and of the types they use from other libraries.
    /// </summary>
    /// <param name="references">The references.</param>
    /// <param name="options">The options.</param>
    /// <returns>The generated files, in a folder per namespace, or a single file with <see cref="LibrarySetOptions.SingleFile"/>.</returns>
    /// <exception cref="CsComException">A reference or a configuration file is not valid, or two libraries have the same namespace.</exception>
    public LibrarySetResult Generate(IReadOnlyList<LibrarySetReference> references, LibrarySetOptions options)
    {
        var set = Prepare(references, options, sanitizeNames: true);
        var namespaces = new Dictionary<TypeDefinition, string>(ReferenceEqualityComparer.Instance);
        foreach (var (entry, _) in set.Libraries)
        {
            foreach (var type in entry.Library.Types)
            {
                namespaces.Add(type, entry.Namespace);
            }
        }

        var eventSources = EventEmitter.GetEventSources(set.Libraries.SelectMany(static l => l.Entry.Library.Types));
        var documents = new List<GeneratedDocument>();
        for (int i = 0; i < set.Libraries.Count; i++)
        {
            var (entry, codeOptions) = set.Libraries[i];
            var scope = new EmitScope { Namespaces = namespaces, EventSources = eventSources, EmitSupportCode = i == 0 };
            foreach (var document in _pipeline.EmitCode(entry.Library, codeOptions, entry.Configuration, scope))
            {
                // The support code is generated with the first library, into its own folder.
                string path = options.SingleFile ? document.RelativePath
                    : document.RelativePath.StartsWith(SupportCodeFolder, StringComparison.Ordinal) ? $"{set.SupportNamespace}/{document.RelativePath[SupportCodeFolder.Length..]}"
                    : $"{entry.Namespace}/{document.RelativePath}";
                documents.Add(document with { RelativePath = path });
            }
        }

        if (options.SingleFile)
        {
            documents = [MergeSingleFile(documents, options, set.Libraries.Select(static l => l.Entry.Library))];
        }

        if (options.DisableRuntimeMarshalling)
        {
            documents.Add(CreateAssemblyAttributes(options));
        }

        return new LibrarySetResult
        {
            Documents = documents,
            Libraries = [.. set.Libraries.Select(static l => Describe(l.Entry))],
            InputFiles = set.InputFiles,
        };
    }

    /// <summary>
    /// Reads the references, merges the types they use from other libraries into a model per library and applies the model
    /// transformers, without generating the code, e.g. to list the names that the selectors of configuration files match.
    /// </summary>
    /// <param name="references">The references.</param>
    /// <param name="options">The options.</param>
    /// <param name="sanitizeNames">Whether the names are made valid and unique C# identifiers, as for the generated code.</param>
    /// <returns>The libraries: the references in order, then the libraries they use.</returns>
    /// <exception cref="CsComException">A reference or a configuration file is not valid, or two libraries have the same namespace.</exception>
    public IReadOnlyList<LibrarySetModel> Transform(IReadOnlyList<LibrarySetReference> references, LibrarySetOptions options, bool sanitizeNames = true) =>
        [.. Prepare(references, options, sanitizeNames).Libraries.Select(static l => new LibrarySetModel(Describe(l.Entry), l.Entry.Library))];

    private static LibrarySetLibrary Describe(LibrarySetEntry entry) => new(
        entry.Library.Name,
        entry.Library.Guid,
        entry.Library.MajorVersion,
        entry.Library.MinorVersion,
        entry.Namespace,
        entry.Reference is not null,
        entry.Library.Types.Count,
        entry.Library.Documentation);

    // Reads and merges the libraries, assigns their configurations and applies their model transformers.
    private PreparedSet Prepare(IReadOnlyList<LibrarySetReference> references, LibrarySetOptions options, bool sanitizeNames)
    {
        ArgumentNullException.ThrowIfNull(references);
        ArgumentNullException.ThrowIfNull(options);
        if (references.Count == 0)
        {
            throw new CsComException("No type library or interop assembly is referenced.");
        }

        var inputFiles = new List<string>();
        var models = new List<(LibrarySetReference, TypeLibrary, PipelineConfiguration)>();
        foreach (var reference in references)
        {
            var library = _pipeline.ReadTypeLibrary(reference.Source, reference.ReferencePaths);
            if (library.Path is { } path)
            {
                inputFiles.Add(TypeLibrarySource.GetFilePath(path));
            }

            models.Add((reference, library, LoadConfiguration(reference.ConfigurationPath, inputFiles)));
        }

        var namespaces = ToDictionary(options.Namespaces);
        var configurationPaths = ToDictionary(options.ConfigurationPaths);
        var entries = LibrarySetMerger.Merge(models, namespaces, _logger);
        foreach (var entry in entries.Where(static e => string.IsNullOrEmpty(e.Reference?.ConfigurationPath)))
        {
            if (configurationPaths.TryGetValue(entry.Library.Name, out string? configurationPath))
            {
                entry.Configuration = LoadConfiguration(configurationPath, inputFiles);
            }
        }

        var names = entries.Select(static e => e.Library.Name).ToHashSet(StringComparer.OrdinalIgnoreCase);
        foreach (string name in namespaces.Keys.Concat(configurationPaths.Keys).Where(n => !names.Contains(n)).Distinct(StringComparer.OrdinalIgnoreCase))
        {
            LogUnknownLibrary(name, string.Join(", ", entries.Select(static e => e.Library.Name)));
        }

        string supportNamespace = options.SupportNamespace ?? entries[0].Namespace + ".ComSupport";
        if (options.SupportCode != SupportCodeMode.Package)
        {
            ProjectGenerator.ValidateNamespace(supportNamespace);
            if (entries.Find(e => string.Equals(e.Namespace, supportNamespace, StringComparison.OrdinalIgnoreCase)) is { } conflict)
            {
                throw new CsComException($"The support code cannot be generated into '{supportNamespace}', the namespace of '{conflict.Library.Name}'.");
            }
        }

        var libraries = new List<(LibrarySetEntry Entry, CodeGenerationOptions Options)>();
        foreach (var entry in entries)
        {
            var codeOptions = CreateOptions(entry, options, supportNamespace);
            if (entry.Reference is null)
            {
                LogGeneratingUsedTypes(entry.Library.Name, entry.Namespace);
            }
            else
            {
                LogGeneratingLibrary(entry.Library.Name, entry.Namespace);
            }

            _pipeline.TransformModel(entry.Library, codeOptions, entry.Configuration, sanitizeNames);
            libraries.Add((entry, codeOptions));
        }

        LibrarySetMerger.ValidateReferences(entries);
        return new PreparedSet(libraries, supportNamespace, [.. inputFiles.Distinct(StringComparer.OrdinalIgnoreCase)]);
    }

    private PipelineConfiguration LoadConfiguration(string? path, List<string> inputFiles)
    {
        if (string.IsNullOrEmpty(path))
        {
            return PipelineConfiguration.Empty;
        }

        string fullPath = Path.GetFullPath(path);
        inputFiles.Add(fullPath);
        return PipelineConfiguration.Load(fullPath, _pipeline.Registry);
    }

    // The names of the libraries are case-insensitive; the last of the names that differ only in case wins.
    private static Dictionary<string, string> ToDictionary(IReadOnlyDictionary<string, string> values)
    {
        var dictionary = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
        foreach (var (name, value) in values)
        {
            dictionary[name] = value;
        }

        return dictionary;
    }

    // Merges the single files of the libraries into one, with a namespace block per namespace.
    private static GeneratedDocument MergeSingleFile(List<GeneratedDocument> documents, LibrarySetOptions options, IEnumerable<TypeLibrary> libraries)
    {
        var members = new List<MemberDeclarationSyntax>();
        foreach (var member in documents.SelectMany(static d => d.Root.Members))
        {
            members.Add(member is FileScopedNamespaceDeclarationSyntax fileScoped
                ? SyntaxFactory.NamespaceDeclaration(fileScoped.Name.WithoutTrivia()).WithUsings(fileScoped.Usings).WithMembers(fileScoped.Members)
                : member.WithoutLeadingTrivia());
        }

        string sources = string.Join(", ", libraries.Select(static l => $"{l.Name} {l.MajorVersion}.{l.MinorVersion} ({l.Guid:B})"));
        string header = $"""
            // <auto-generated>
            //     This code was generated by CsCom {options.ToolVersion} from the type libraries {sources}.
            //     Changes to this file may cause incorrect behavior and will be lost if the code is regenerated.
            // </auto-generated>

            #nullable enable
            {(options.SuppressedWarnings.Count > 0 ? $"#pragma warning disable {string.Join(", ", options.SuppressedWarnings)}{Environment.NewLine}" : string.Empty)}

            """;
        return new GeneratedDocument(options.SingleFileName, SyntaxFormatter.Format(SyntaxFactory.CompilationUnit().WithMembers(SyntaxFactory.List(members)), header));
    }

    private static CodeGenerationOptions CreateOptions(LibrarySetEntry entry, LibrarySetOptions options, string supportNamespace)
    {
        var reference = entry.Reference;
        return new CodeGenerationOptions
        {
            Namespace = entry.Namespace,
            LanguageVersion = options.LanguageVersion,
            SupportCode = options.SupportCode,
            SupportNamespace = supportNamespace,
            SingleFile = options.SingleFile,
            SingleFileName = options.SingleFileName,
            Marshalling = reference?.Marshalling.Apply(options.Marshalling) ?? options.Marshalling,
            EventStyle = reference?.EventStyle ?? options.EventStyle,
            StructProperties = reference?.StructProperties ?? options.StructProperties,
            OverloadsForDefaultValues = reference?.OverloadsForDefaultValues ?? options.OverloadsForDefaultValues,
            SuppressedWarnings = options.SuppressedWarnings,
            ToolVersion = options.ToolVersion,
        };
    }

    private static GeneratedDocument CreateAssemblyAttributes(LibrarySetOptions options)
    {
        string text = $"""
            // <auto-generated>
            //     This code was generated by CsCom {options.ToolVersion}.
            //     Changes to this file may cause incorrect behavior and will be lost if the code is regenerated.
            // </auto-generated>

            // Source-generated COM interop marshals VARIANT and DECIMAL values only when runtime marshalling is disabled.
            [assembly: global::System.Runtime.CompilerServices.DisableRuntimeMarshalling]

            """;
        return new GeneratedDocument(AssemblyAttributesFileName, SyntaxFactory.ParseCompilationUnit(text.ReplaceLineEndings(SyntaxFormatter.EndOfLine)));
    }

    [LoggerMessage(Level = LogLevel.Information, Message = "Generating '{Library}' into '{Namespace}'")]
    private partial void LogGeneratingLibrary(string library, string @namespace);

    [LoggerMessage(Level = LogLevel.Information, Message = "Generating the types used from '{Library}' into '{Namespace}'")]
    private partial void LogGeneratingUsedTypes(string library, string @namespace);

    [LoggerMessage(Level = LogLevel.Warning, Message = "No generated library is named '{Name}'; the libraries are {Libraries}")]
    private partial void LogUnknownLibrary(string name, string libraries);

    private sealed record PreparedSet(List<(LibrarySetEntry Entry, CodeGenerationOptions Options)> Libraries, string SupportNamespace, List<string> InputFiles);
}
