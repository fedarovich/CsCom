using System.Text.Json;
using System.Text.Json.Serialization;
using CsCom.CodeGeneration;

namespace CsCom.Output;

/// <summary>
/// The <c>cscom.json</c> file that records how a project was generated, so that it can be updated later.
/// </summary>
public sealed record CsComManifest
{
    /// <summary>The name of the manifest file.</summary>
    public const string FileName = "cscom.json";

    /// <summary>The version of the tool that generated the project.</summary>
    public required string ToolVersion { get; init; }

    // The JSON source generator sets init-only properties that are missing from the JSON to null,
    // so the properties added to the manifest later fall back to their defaults.
    private readonly IReadOnlyList<string> _sources = [];
    private readonly IReadOnlyList<string> _runtimeIdentifiers = [];
    private readonly MarshallingOptions _marshalling = new();

    /// <summary>
    /// The sources the project was generated from: the full paths of files, or registered LIBIDs or ProgIDs, which are looked
    /// up again when the project is updated.
    /// </summary>
    public IReadOnlyList<string> Sources { get => _sources; init => _sources = value ?? []; }

    /// <summary>The single source of the projects generated by earlier versions, which is read as <see cref="Sources"/>.</summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    public string? TypeLibrary { get; init; }

    /// <summary>The project and assembly name.</summary>
    public required string Name { get; init; }

    /// <summary>The namespace of the single source of the projects generated by earlier versions.</summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    public string? Namespace { get; init; }

    /// <summary>
    /// The namespaces of libraries by their names; the other libraries use <c>Interop.&lt;Library&gt;</c>. Omitted when there are none.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    public IReadOnlyDictionary<string, string>? Namespaces { get; init; }

    /// <summary>The target frameworks.</summary>
    public required IReadOnlyList<string> TargetFrameworks { get; init; }

    /// <summary>The runtime identifiers.</summary>
    public IReadOnlyList<string> RuntimeIdentifiers { get => _runtimeIdentifiers; init => _runtimeIdentifiers = value ?? []; }

    /// <summary>The C# version.</summary>
    public required int LanguageVersion { get; init; }

    /// <summary>Whether all types are generated into a single file.</summary>
    public bool SingleFile { get; init; }

    /// <summary>Where the support code comes from.</summary>
    [JsonConverter(typeof(CamelCaseEnumConverter<SupportCodeMode>))]
    public SupportCodeMode SupportCode { get; init; }

    /// <summary>How <c>DATE</c>, <c>CURRENCY</c> and <c>VARIANT_BOOL</c> values are represented; the defaults when missing.</summary>
    public MarshallingOptions Marshalling { get => _marshalling; init => _marshalling = value ?? new(); }

    /// <summary>The code generated for the event (source) interfaces; <see cref="EventStyle.Events"/> when missing.</summary>
    [JsonConverter(typeof(CamelCaseEnumConverter<EventStyle>))]
    public EventStyle EventStyle { get; init; }

    /// <summary>Whether the members of the generated structures that are converted to .NET types are properties; <see cref="StructProperties.Auto"/> when missing.</summary>
    [JsonConverter(typeof(StructPropertiesConverter))]
    public StructProperties StructProperties { get; init; }

    /// <summary>Whether overloads are generated for the default values that C# cannot express; <see langword="false"/> when missing.</summary>
    public bool OverloadsForDefaultValues { get; init; }

    /// <summary>The configuration file of the single source of the projects generated by earlier versions, relative to the project directory.</summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    public string? Configuration { get; init; }

    /// <summary>
    /// The configuration files with the transformers of libraries by their names, relative to the project directory; omitted
    /// when there are none.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    public IReadOnlyDictionary<string, string>? Configurations { get; init; }

    /// <summary>
    /// For interop assemblies, the assemblies or directories that contain the assemblies they reference, relative to the
    /// project directory; omitted when there are none.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    public IReadOnlyList<string>? ReferencePaths { get; init; }

    /// <summary>
    /// Gets the sources, including the single source of the projects generated by earlier versions.
    /// </summary>
    public IReadOnlyList<string> GetSources() => Sources.Count > 0 ? Sources : TypeLibrary is null ? [] : [TypeLibrary];

    /// <summary>
    /// Reads the manifest from the project directory.
    /// </summary>
    public static CsComManifest Read(string projectDirectory)
    {
        string path = Path.Combine(projectDirectory, FileName);
        if (!File.Exists(path))
        {
            throw new CsComException($"'{path}' was not found. Only the projects created with 'cscom project create' can be updated.");
        }

        try
        {
            return JsonSerializer.Deserialize(File.ReadAllText(path), CsComJsonContext.Default.CsComManifest)
                ?? throw new CsComException($"'{path}' is empty.");
        }
        catch (JsonException e)
        {
            throw new CsComException($"'{path}' is not valid: {e.Message}", e);
        }
    }

    /// <summary>
    /// Writes the manifest into the project directory.
    /// </summary>
    public void Write(string projectDirectory)
    {
        string json = JsonSerializer.Serialize(this, CsComJsonContext.Default.CsComManifest);
        File.WriteAllText(Path.Combine(projectDirectory, FileName), json.ReplaceLineEndings() + Environment.NewLine);
    }
}

[JsonSourceGenerationOptions(
    PropertyNamingPolicy = JsonKnownNamingPolicy.CamelCase,
    WriteIndented = true,
    DefaultIgnoreCondition = JsonIgnoreCondition.Never,
    Converters = [typeof(CamelCaseEnumConverter<ValueMarshalling>), typeof(CamelCaseEnumConverter<BstrMarshalling>), typeof(CamelCaseEnumConverter<SafeArrayMarshalling>)])]
[JsonSerializable(typeof(CsComManifest))]
internal sealed partial class CsComJsonContext : JsonSerializerContext
{
}

internal sealed class CamelCaseEnumConverter<TEnum>() : JsonStringEnumConverter<TEnum>(JsonNamingPolicy.CamelCase, allowIntegerValues: false)
    where TEnum : struct, Enum
{
}

// Also reads the values of earlier versions, nonblittable and always, as auto, so that their projects can be updated.
internal sealed class StructPropertiesConverter : JsonConverter<StructProperties>
{
    public override StructProperties Read(ref Utf8JsonReader reader, Type typeToConvert, JsonSerializerOptions options) => reader.GetString() switch
    {
        "auto" or "nonblittable" or "always" => StructProperties.Auto,
        "never" => StructProperties.Never,
        var value => throw new JsonException($"'{value}' is not a valid value of structProperties: auto or never is expected."),
    };

    public override void Write(Utf8JsonWriter writer, StructProperties value, JsonSerializerOptions options) =>
        writer.WriteStringValue(value == StructProperties.Never ? "never" : "auto");
}
